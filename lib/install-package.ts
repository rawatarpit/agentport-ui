/**
 * The install artifact is a discovery package, not a runtime.
 *
 * It may describe what the merchant exposed and where the hosted governor
 * lives. It must never contain a policy decision, a credential, a ledger, an
 * approval queue, or an execution path. The Rust governor remains the only
 * thing that answers "is this allowed?" and the only writer to the ledger.
 */
export type InstallFile = { path: string; content: string }

export type PublishTarget = {
  /** Package root relative to the repository root. Empty for a single-package repo. */
  root?: string
  dir: string
  mode: 'direct' | 'build-output'
  framework: string
  /** More than one framework package matched; the caller must ask, not guess. */
  ambiguous?: boolean
}

export type InstallPackage = {
  files: InstallFile[]
  target: PublishTarget
  manifest: Record<string, unknown>
  config: Record<string, unknown>
  summary: string[]
}

export type InstallPackageInput = {
  drafts: { rules?: unknown; setup?: unknown; capabilities?: unknown }
  tenantId: string
  business: string
  siteUrl?: string | null
  workerUrl: string
  publishTarget?: PublishTarget
  packageJson?: string | null
  existingManifest?: string | null
  existingAccessPage?: string | null
  existingLlms?: string | null
  now?: Date
}

