function publishScript(): string {
  return `#!/usr/bin/env node
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const packageRoot = dirname(here)
const config = JSON.parse(readFileSync(join(here, 'config.json'), 'utf8'))
const target = config.publishDir === '.' ? packageRoot : join(packageRoot, config.publishDir)
const at = (rel) => join(target, rel)
const fail = (message) => { console.error('agentport: ' + message); process.exit(1) }

// The hosted governor is the source of truth. Copying agentport/manifest.json
// would let a stale snapshot advertise capabilities the client never selected,
// and the site would promise what the governor refuses. Fetch the live manifest
// and fail closed when it cannot be read.
const res = await fetch(config.manifestUrl, { headers: { accept: 'application/json' } }).catch(() => null)
if (res === null || !res.ok) fail('could not read the hosted manifest; refusing to publish a stale snapshot')
const text = await res.text()
let live
try { live = JSON.parse(text) } catch { fail('hosted manifest is not valid JSON') }
if (live.version !== '1.0') fail('hosted manifest version is not 1.0')
if (live.business !== config.business) fail('hosted manifest is for a different business')
if (live.authentication?.scheme !== 'bearer') fail('hosted manifest does not advertise bearer authentication')

const business = String(live.business ?? config.business)
const manifestUrl = String(live.endpoints?.manifest ?? config.manifestUrl)
const executeUrl = String(live.endpoints?.execute ?? config.executeUrl)
const tokenUrl = String(live.endpoints?.token ?? live.authentication?.tokenEndpoint ?? '')
const autoIssue = Array.isArray(live.authentication?.autoIssue) ? live.authentication.autoIssue : []
const esc = (value) => String(value)
  .replace(/&/g, '&amp;')
  .replace(/</g, '&lt;')
  .replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;')
  .replace(/'/g, '&#39;')

mkdirSync(join(target, '.well-known'), { recursive: true })
writeFileSync(at('.well-known/agent.json'), text)

// The manifest is fetched live, so the digest recorded at install time is
// stale the moment the governor republishes. Update it with the bytes we just
// wrote; otherwise a reviewer comparing the two would see a false mismatch.
const digest = createHash('sha256').update(text).digest('hex')
if (config.manifestSha256 !== digest) {
  config.manifestSha256 = digest
  writeFileSync(join(here, 'config.json'), JSON.stringify(config, null, 2) + '\\n')
}

const html = [
  '<!doctype html>',
  '<html lang="en">',
  '<head>',
  '  <meta charset="utf-8">',
  '  <meta name="viewport" content="width=device-width, initial-scale=1">',
  '  <title>Agent access — ' + esc(business) + '</title>',
  '  <link rel="alternate" type="application/json" href="' + esc(manifestUrl) + '">',
  '  <meta name="agentport-manifest" content="' + esc(manifestUrl) + '">',
  '</head>',
  '<body>',
  '  <h1>' + esc(business) + ' — agent access</h1>',
  '  <p>Agents use the manifest below. Every call is authorised and recorded by Agent Port.</p>',
  '  <p><a href="' + esc(manifestUrl) + '">' + esc(manifestUrl) + '</a></p>',
  ...(tokenUrl === '' ? [] : [
    '  <p>Token endpoint: <a href="' + esc(tokenUrl) + '">' + esc(tokenUrl) + '</a></p>',
    '  <p>Only public read capabilities are auto-issued. Writes and private reads require a human grant.</p>',
  ]),
  '  <!-- generated by agentport -->',
  '</body>',
  '</html>',
  '',
].join('\\n')
writeFileSync(at('.well-known/agent-access.html'), html)

const begin = '<!-- agentport:begin -->'
const end = '<!-- agentport:end -->'
const block = [
  begin,
  '# Agent access — ' + business,
  '',
  'Canonical manifest: ' + manifestUrl,
  'Execute: ' + executeUrl,
  '',
  tokenUrl === ''
    ? 'Authentication: a business-issued, short-lived credential with named scopes.'
    : 'Authentication: call the token endpoint below with a capability name and a self-declared agent name. The governor returns a 5-minute bearer scoped to that capability. Only public read capabilities are auto-issued; writes and private reads require a human grant. The self-declared name is audit metadata, not a verified identity.',
  ...(tokenUrl === '' ? [] : [
    '',
    'Token: ' + tokenUrl,
    'Request body: {"capability":"' + (autoIssue[0] || '<capability>') + '","agent":{"name":"your-agent"}}',
    'Content-Type: application/json',
  ]),
  ...(autoIssue.length === 0 ? [] : ['', 'Auto-issued public reads: ' + autoIssue.join(', ')]),
  '',
  'Every call is evaluated and recorded by the hosted Agent Port governor.',
  'This file is a discovery pointer. It makes no policy decision.',
  end,
].join('\\n')
const llmsPath = at('llms.txt')
if (existsSync(llmsPath)) {
  const current = readFileSync(llmsPath, 'utf8')
  const start = current.indexOf(begin)
  const finish = current.indexOf(end)
  if (start >= 0 && finish > start) {
    writeFileSync(llmsPath, current.slice(0, start) + block + current.slice(finish + end.length))
  } else {
    writeFileSync(llmsPath, current.trimEnd() + '\\n\\n' + block + '\\n')
  }
} else {
  writeFileSync(llmsPath, block + '\\n')
}
console.log('agentport: wrote the hosted governor manifest into ' + config.publishDir)
`
}

function verifyScript(): string {
  return `#!/usr/bin/env node
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const packageRoot = dirname(here)
const config = JSON.parse(readFileSync(join(here, 'config.json'), 'utf8'))
const target = config.publishDir === '.' ? packageRoot : join(packageRoot, config.publishDir)
const at = (rel) => join(target, rel)
const fail = (message) => { console.error('agentport: ' + message); process.exit(1) }
const get = async (url) => {
  const res = await fetch(url, { headers: { accept: 'application/json' } })
  if (!res.ok) fail(url + ' returned ' + res.status)
  return res
}

// generatedAt changes between governor reads; it is not part of the selection.
const canon = (value) => {
  if (Array.isArray(value)) return value.map(canon)
  if (value !== null && typeof value === 'object') {
    const out = {}
    for (const key of Object.keys(value).sort()) {
      if (key !== 'generatedAt') out[key] = canon(value[key])
    }
    return out
  }
  return value
}

const live = await (await get(config.manifestUrl)).json()
if (live.version !== '1.0') fail('hosted manifest version is not 1.0')
if (live.business !== config.business) fail('hosted manifest is for a different business')
if (live.authentication?.scheme !== 'bearer') fail('hosted manifest does not advertise bearer authentication')

let served
if (config.siteUrl) {
  served = await (await get(new URL('/.well-known/agent.json', config.siteUrl).toString())).json()
} else {
  try {
    served = JSON.parse(readFileSync(at('.well-known/agent.json'), 'utf8'))
  } catch {
    fail('no published manifest found; run publish first')
  }
}
if (JSON.stringify(canon(served)) !== JSON.stringify(canon(live))) {
  fail('published manifest does not match the hosted governor selection')
}
console.log('agentport: discovery verified against the hosted governor')
`
}

export function buildInstallPackageFrom(
  input: InstallPackageInput,
): { ok: true; value: InstallPackage } | { ok: false; reason: string } {
  const tenantId = (input.tenantId ?? '').trim()
  if (!tenantId) return { ok: false, reason: 'Tenant is missing; sign in again.' }
  const business = (input.business ?? '').trim()
  if (!business) return { ok: false, reason: 'Business name is missing; set it before opening an install PR.' }

  const worker = normaliseWorkerUrl(input.workerUrl, tenantId)
  if (!worker.ok) return worker
  const site = normaliseSiteUrl(input.siteUrl)
  if (!site.ok) return site

  const compiled = compileLiveFrom(input.drafts)
  if (!compiled.ok) return compiled

  const target = input.publishTarget ?? {
    root: '',
    dir: '.',
    mode: 'direct',
    framework: 'static-root',
  }
  if (target.ambiguous) {
    return {
      ok: false,
      reason:
        'More than one website package matched. Pick the package that serves the site before opening an install PR.',
    }
  }
  const root = (target.root ?? '').replace(/^\/+|\/+$/g, '')
  const dir = target.dir === '.' ? '.' : target.dir.replace(/^\/+|\/+$/g, '')
  if (root !== '' && !isSafeRepoPath(`${root}/.keep`)) {
    return { ok: false, reason: 'Package root is not a safe repository path.' }
  }
  if (dir !== '.' && !isSafeRepoPath(`${dir}/.keep`)) {
    return { ok: false, reason: 'Publish directory is not a safe repository path.' }
  }

  if (input.existingManifest) {
    try {
      const existing = JSON.parse(input.existingManifest) as { generatedBy?: unknown }
      if (existing.generatedBy !== 'agentport') {
        return {
          ok: false,
          reason:
            'A different agent manifest already exists at this path. Refusing to overwrite it; move it or remove it first.',
        }
      }
    } catch {
      return {
        ok: false,
        reason:
          'An existing agent manifest is not valid JSON. Refusing to overwrite it; review it first.',
      }
    }
  }
  if (input.existingAccessPage && !input.existingAccessPage.includes(AGENT_ACCESS_MARKER)) {
    return {
      ok: false,
      reason:
        'A different agent-access page already exists. Refusing to overwrite it; move it or remove it first.',
    }
  }

  const now = input.now ?? new Date()
  const manifestUrl = `${worker.url}/.well-known/agent.json`
  const executeUrl = `${worker.url}/.well-known/agent/invoke`
  const details = capabilityDetails(compiled.compiled, input.drafts)
  const policy = compiled.compiled.policy
  const manifest: Record<string, unknown> = {
    version: '1.0',
    generatedBy: 'agentport',
    business,
    baseUrl: worker.url,
    generatedAt: now.toISOString(),
    capabilities: details,
    authentication: {
      scheme: 'bearer',
      header: 'Authorization',
      note: 'Send a short-lived scoped token. An agent is not trusted because it is an AI agent; it is trusted because the business issued it a credential with named scopes.',
    },
    policies: {
      ...(policy.maxOrderValue ? { maxOrderValue: policy.maxOrderValue } : {}),
      ...(policy.absoluteMaxOrderValue
        ? { absoluteMaxOrderValue: policy.absoluteMaxOrderValue }
        : {}),
      ...(policy.bulkOrderThreshold ? { bulkOrderThreshold: policy.bulkOrderThreshold } : {}),
      ...(policy.rateLimit ? { rateLimit: policy.rateLimit } : {}),
      requiresApproval: policy.alwaysRequireApproval ?? [],
      forbidden: policy.forbiddenCapabilities ?? [],
      restrictedDataClasses: policy.restrictedDataClasses ?? [],
    },
    errorContract: DENIAL_REASONS.map(([reason, detail]) => ({ reason, detail })),
    endpoints: { manifest: manifestUrl, execute: executeUrl },
    note: 'Advisory discovery snapshot. The hosted governor serves the authoritative manifest and makes every decision.',
  }
  const manifestContent = `${JSON.stringify(manifest, null, 2)}\n`
  const manifestSha256 = createHash('sha256').update(manifestContent).digest('hex')
  const config: Record<string, unknown> = {
    version: 1,
    generatedBy: 'agentport',
    tenantId,
    business,
    siteUrl: site.url,
    workerUrl: worker.url,
    manifestUrl,
    executeUrl,
    manifestSha256,
    packageRoot: root === '' ? '.' : root,
    publishDir: dir,
    issuedAt: now.toISOString(),
    enforcement: 'hosted',
    note: 'Discovery only. No policy decision, credential, ledger, approval queue or execution path lives here.',
  }

  const normalisedTarget: PublishTarget = { ...target, root, dir }
  const packagePrefix = root === '' ? '' : `${root}/`
  const prefix = targetPrefix(normalisedTarget)
  const packageJsonPath = `${packagePrefix}package.json`
  const files: InstallFile[] = [
    { path: `${packagePrefix}agentport/manifest.json`, content: manifestContent },
    { path: `${packagePrefix}agentport/config.json`, content: `${JSON.stringify(config, null, 2)}\n` },
    { path: `${packagePrefix}agentport/llms.txt`, content: llmsTxt(business, manifestUrl, executeUrl) },
    { path: `${packagePrefix}agentport/agent-access.html`, content: agentAccessHtml(business, manifestUrl) },
    { path: `${packagePrefix}agentport/publish.mjs`, content: publishScript() },
    { path: `${packagePrefix}agentport/verify.mjs`, content: verifyScript() },
    { path: `${packagePrefix}agentport/README.md`, content: readme(business, manifestUrl, normalisedTarget) },
  ]

  if (target.mode === 'direct') {
    files.push(
      { path: `${prefix}.well-known/agent.json`, content: manifestContent },
      { path: `${prefix}.well-known/agent-access.html`, content: agentAccessHtml(business, manifestUrl) },
      { path: `${prefix}llms.txt`, content: mergeLlmsTxt(input.existingLlms, llmsTxt(business, manifestUrl, executeUrl)) },
    )
    // Keep the folder self-updating. A framework site runs `publish.mjs` before
    // its build and rewrites the served files from the live governor, so the
    // snapshot cannot advertise capabilities the merchant has since changed.
    // A static-root site has no build, so it relies on `agentport:publish` and
    // the dashboard/PR path instead of a lifecycle hook.
    if (input.packageJson) {
      const hooked = addDirectRefreshHook(input.packageJson, target.framework !== 'static-root')
      if (!hooked.ok) return hooked
      files.push({ path: packageJsonPath, content: hooked.content })
    }
  } else {
    if (!input.packageJson) {
      return {
        ok: false,
        reason: `This site builds to ${dir}/, so the install needs a postbuild hook, but ${packageJsonPath} was not found.`,
      }
    }
    const hooked = addBuildHook(input.packageJson)
    if (!hooked.ok) return hooked
    files.push({ path: packageJsonPath, content: hooked.content })
  }

  for (const file of files) {
    if (!isSafeRepoPath(file.path)) {
      return { ok: false, reason: `Refusing to write an unsafe path: ${file.path}` }
    }
  }
  const unique = new Set(files.map((f) => f.path))
  if (unique.size !== files.length) {
    return { ok: false, reason: 'Install package contains duplicate file paths.' }
  }

  return {
    ok: true,
    value: { files, target: normalisedTarget, manifest, config, summary: compiled.compiled.summary },
  }
}

/**
 * A single-file manual path for merchants who are not ready to grant the App
 * repo access. It writes the same package; it does not evaluate anything.
 */
export function buildManualInstaller(files: InstallFile[]): string {
  const payload = JSON.stringify(files)
  return `#!/usr/bin/env node
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

const files = ${payload}
for (const file of files) {
  const target = join(process.cwd(), file.path)
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, file.content, { encoding: 'utf8', mode: 0o644 })
}
console.log('agentport: wrote ' + files.length + ' files. Review the diff, then commit.')
`
}
