const AGENT_ACCESS_MARKER = '<!-- generated by agentport -->'

export function normaliseWorkerUrl(
  raw: string,
  tenantId?: string,
): { ok: true; url: string } | { ok: false; reason: string } {
  const value = (raw ?? '').trim()
  if (!value) return { ok: false, reason: 'AGENTPORT_WORKER_URL is not set — the hosted governor URL is required.' }
  let parsed: URL
  try {
    parsed = new URL(value)
  } catch {
    return { ok: false, reason: 'AGENTPORT_WORKER_URL is not a valid absolute URL.' }
  }
  if (parsed.protocol !== 'https:' && parsed.protocol !== 'http:') {
    return { ok: false, reason: 'AGENTPORT_WORKER_URL must be http or https.' }
  }
  if (parsed.protocol === 'http:' && !['localhost', '127.0.0.1', '::1'].includes(parsed.hostname)) {
    return { ok: false, reason: 'AGENTPORT_WORKER_URL must use https outside local development.' }
  }
  if (parsed.username || parsed.password || parsed.search || parsed.hash) {
    return { ok: false, reason: 'AGENTPORT_WORKER_URL must not carry credentials, a query or a fragment.' }
  }

  const path = parsed.pathname.replace(/\/+$/, '') || '/'
  if (tenantId === undefined) {
    return { ok: true, url: parsed.toString().replace(/\/$/, '') }
  }
  const tenant = tenantId.trim()
  if (!tenant) return { ok: false, reason: 'Tenant is missing; sign in again.' }
  const expected = `/t/${encodeURIComponent(tenant)}`
  if (path !== '/' && path !== expected) {
    return {
      ok: false,
      reason:
        path.startsWith('/t/')
          ? 'AGENTPORT_WORKER_URL names a different tenant than the signed-in workspace.'
          : 'AGENTPORT_WORKER_URL must be the hosted governor origin, not a path.',
    }
  }
  parsed.pathname = expected
  return { ok: true, url: parsed.toString().replace(/\/$/, '') }
}

function normaliseSiteUrl(raw: string | null | undefined): { ok: true; url: string | null } | { ok: false; reason: string } {
  if (raw === null || raw === undefined || raw.trim() === '') return { ok: true, url: null }
  const value = raw.trim()
  let parsed: URL
  try {
    parsed = new URL(value)
  } catch {
    return { ok: false, reason: 'The site URL is not a valid absolute URL.' }
  }
  if (parsed.protocol !== 'https:' && parsed.protocol !== 'http:') {
    return { ok: false, reason: 'The site URL must be http or https.' }
  }
  if (parsed.protocol === 'http:' && !['localhost', '127.0.0.1', '::1'].includes(parsed.hostname)) {
    return { ok: false, reason: 'The site URL must use https outside local development.' }
  }
  return { ok: true, url: parsed.toString().replace(/\/$/, '') }
}

/**
 * Pick where a framework serves static files. `public` and `static` are source
 * directories, so writing directly is enough. `out`/`dist`/`build` are build
 * outputs, so the package adds one postbuild hook instead of committing files
 * the next build would delete.
 *
 * A monorepo is inspected one level deeper: `apps/web/next.config.mjs` wins
 * over the repository root. If two packages both look like websites, the
 * caller gets `ambiguous` and must ask rather than commit into the wrong one.
 */
export function detectPublishTarget(paths: string[]): PublishTarget {
  const roots = new Set<string>([''])
  for (const path of paths) {
    const pkg = /^((?:[^/]+\/){1,2})package\.json$/.exec(path)
    if (pkg) roots.add(pkg[1]!.replace(/\/$/, ''))
    const config = /^((?:[^/]+\/){0,2})(?:next|vite|astro|nuxt|remix|svelte|gatsby)\.config\.[^.]+$/.exec(path)
    if (config) roots.add(config[1]!.replace(/\/$/, ''))
  }

  const candidates = [...roots]
    .sort((a, b) => a.split('/').length - b.split('/').length || a.localeCompare(b))
    .map((root) => targetAt(paths, root))
  const frameworkCandidates = candidates.filter(
    (target) => !['static', 'static-export', 'bundler', 'static-root'].includes(target.framework),
  )
  if (frameworkCandidates.length > 1) {
    return { ...frameworkCandidates[0]!, ambiguous: true }
  }
  if (frameworkCandidates.length === 1) return frameworkCandidates[0]!
  const nonDefault = candidates.find((target) => target.framework !== 'static-root')
  return nonDefault ?? candidates[0]!
}

function targetAt(paths: string[], root: string): PublishTarget {
  const at = (name: string): string => (root ? `${root}/${name}` : name)
  const hasFile = (name: string): boolean => paths.includes(name)
  const hasPrefix = (prefix: string): boolean =>
    paths.some((p) => p === prefix || p.startsWith(`${prefix}/`))
  const hasConfig = (base: string): boolean =>
    ['.js', '.mjs', '.cjs', '.ts', '.mts', '.cts'].some((ext) => hasFile(at(`${base}${ext}`)))
  const target = (dir: string, mode: PublishTarget['mode'], framework: string): PublishTarget => ({
    root,
    dir,
    mode,
    framework,
  })

  if (hasConfig('next.config')) return target('public', 'direct', 'next')
  if (hasConfig('vite.config')) return target('public', 'direct', 'vite')
  if (hasConfig('astro.config')) return target('public', 'direct', 'astro')
  if (hasConfig('nuxt.config')) return target('public', 'direct', 'nuxt')
  if (hasConfig('remix.config')) return target('public', 'direct', 'remix')
  if (hasConfig('svelte.config')) return target('static', 'direct', 'sveltekit')
  if (hasConfig('gatsby-config')) return target('static', 'direct', 'gatsby')
  if (hasPrefix(at('public'))) return target('public', 'direct', 'static')
  if (hasPrefix(at('static'))) return target('static', 'direct', 'static')
  if (hasPrefix(at('out'))) return target('out', 'build-output', 'static-export')
  if (hasPrefix(at('dist'))) return target('dist', 'build-output', 'bundler')
  if (hasPrefix(at('build'))) return target('build', 'build-output', 'bundler')
  return target('.', 'direct', 'static-root')
}

function addBuildHook(packageJson: string): { ok: true; content: string } | { ok: false; reason: string } {
  let parsed: unknown
  try {
    parsed = JSON.parse(packageJson)
  } catch {
    return { ok: false, reason: 'package.json is not valid JSON; refusing to rewrite it.' }
  }
  if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) {
    return { ok: false, reason: 'package.json is not a JSON object; refusing to rewrite it.' }
  }
  const root = parsed as Record<string, unknown>
  const currentScripts =
    typeof root.scripts === 'object' && root.scripts !== null && !Array.isArray(root.scripts)
      ? ({ ...(root.scripts as Record<string, unknown>) } as Record<string, unknown>)
      : {}
  currentScripts['agentport:publish'] = 'node agentport/publish.mjs'
  const post = typeof currentScripts.postbuild === 'string' ? currentScripts.postbuild : ''
  if (!post.includes('agentport/publish.mjs')) {
    currentScripts.postbuild = post
      ? `${post} && node agentport/publish.mjs`
      : 'node agentport/publish.mjs'
  }
  root.scripts = currentScripts
  return { ok: true, content: `${JSON.stringify(root, null, 2)}\n` }
}

/**
 * Direct installs write into a source directory (`public/`, `static/`) that the
 * framework copies into its build output. A `prebuild` hook that runs
 * `publish.mjs` therefore refreshes the served manifest from the live governor
 * on every deploy, so the committed snapshot cannot freeze at the day the
 * install PR was opened.
 *
 * `static-root` sites have no build to hook; they get the `agentport:publish`
 * script and refresh by running it before deploy, or by re-opening the install
 * PR from the dashboard.
 */
function addDirectRefreshHook(
  packageJson: string,
  hookBuild: boolean,
): { ok: true; content: string } | { ok: false; reason: string } {
  let parsed: unknown
  try {
    parsed = JSON.parse(packageJson)
  } catch {
    return { ok: false, reason: 'package.json is not valid JSON; refusing to rewrite it.' }
  }
  if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) {
    return { ok: false, reason: 'package.json is not a JSON object; refusing to rewrite it.' }
  }
  const root = parsed as Record<string, unknown>
  const currentScripts =
    typeof root.scripts === 'object' && root.scripts !== null && !Array.isArray(root.scripts)
      ? ({ ...(root.scripts as Record<string, unknown>) } as Record<string, unknown>)
      : {}
  currentScripts['agentport:publish'] = 'node agentport/publish.mjs'
  if (hookBuild) {
    const pre = typeof currentScripts.prebuild === 'string' ? currentScripts.prebuild : ''
    if (!pre.includes('agentport/publish.mjs')) {
      currentScripts.prebuild = pre
        ? `node agentport/publish.mjs && ${pre}`
        : 'node agentport/publish.mjs'
    }
  }
  root.scripts = currentScripts
  return { ok: true, content: `${JSON.stringify(root, null, 2)}\n` }
}

function capabilityDetails(compiled: Compiled, drafts: InstallPackageInput['drafts']) {
  const policy = compiled.policy
  let extra: Array<{
    name: string
    method: string
    path: string
    kind: 'read' | 'write'
    dataClass: DataClass
    autoIssue: boolean
    allowUnattended?: boolean
  }> = []
  if (drafts.capabilities) {
    const validated = validateCapabilities(drafts.capabilities)
    if (validated.ok) extra = validated.value.extra ?? []
  }
  // Only a mapped route has an execution path in the hosted governor. The
  // known catalogue is there for the policy and the console's vocabulary; a
  // static manifest that advertises `createOrder` when no route implements it
  // sends an agent to a capability the worker cannot execute.
  const routeBacked = new Set(extra.map((e) => e.name))
  return compiled.capabilities
    .filter((cap) => routeBacked.has(cap.name))
    .map((cap) => {
      const known = KNOWN_CAPABILITIES.find((c) => c.name === cap.name)
      const mapped = extra.find((c) => c.name === cap.name)
      // A mapped route carries the merchant's explicit classification. The
      // known catalogue is only a fallback for a name that also has a route.
      const dataClass: DataClass = mapped?.dataClass ?? known?.dataClass ?? 'internal'
      return {
        name: cap.name,
        description:
          known?.description ??
          (mapped ? `Mapped capability ${mapped.method} ${mapped.path}.` : `Capability ${cap.name}.`),
        access: known?.kind ?? mapped?.kind ?? 'write',
        dataClass,
        requiresApproval: (policy.alwaysRequireApproval ?? []).includes(cap.name),
        autoIssue: mapped?.autoIssue === true,
        // The static package has no per-capability input schema. `hiddenFields`
        // is a redaction list, not an input shape, and renaming it to `input`
        // would tell agents the wrong thing. The hosted manifest carries the
        // authoritative shape; `null` here means unknown, not "no input".
        input: null,
      }
    })
}

function escapeMarkdown(value: string): string {
  return value.replace(/[\\`*_{}\[\]<>#|]/g, '\\$&')
}

