import { createHash } from 'node:crypto'
import type { DataClass } from '@/lib/contracts'
import {
  KNOWN_CAPABILITIES,
  compileLiveFrom,
  validateCapabilities,
  type Compiled,
} from '@/lib/golive'
import { isSafeRepoPath } from '@/lib/repo-path'

/**
 * The install artifact is a discovery package, not a runtime.
 *
 * It may describe what the merchant exposed and where the hosted governor
 * lives. It must never contain a policy decision, a credential, a ledger, an
 * approval queue, or an execution path. The Rust governor remains the only
 * thing that answers "is this allowed?" and the only writer to the ledger.
 */
export type InstallFile = { path: string; content: string }

export type PublishTarget = {
  /** Package root relative to the repository root. Empty for a single-package repo. */
  root?: string
  dir: string
  mode: 'direct' | 'build-output'
  framework: string
  /** More than one framework package matched; the caller must ask, not guess. */
  ambiguous?: boolean
}

export type InstallPackage = {
  files: InstallFile[]
  target: PublishTarget
  manifest: Record<string, unknown>
  config: Record<string, unknown>
  summary: string[]
}

export type InstallPackageInput = {
  drafts: { rules?: unknown; setup?: unknown; capabilities?: unknown }
  tenantId: string
  business: string
  siteUrl?: string | null
  workerUrl: string
  publishTarget?: PublishTarget
  packageJson?: string | null
  existingManifest?: string | null
  existingAccessPage?: string | null
  existingLlms?: string | null
  now?: Date
}

const DENIAL_REASONS = [
  ['unknown_capability', 'The capability is not registered.'],
  ['capability_not_exposed', 'The capability exists but is not exposed to agents.'],
  ['unauthenticated', 'No business-issued credential was presented.'],
  ['identity_expired', 'The credential has expired.'],
  ['insufficient_scope', 'The credential does not carry the required scope.'],
  ['delegation_insufficient', 'The represented user did not grant enough scope.'],
  ['policy_denied', 'A merchant policy rule refused the request.'],
  ['rate_limited', 'The caller exceeded its configured rate.'],
  ['approval_required', 'A human decision is required before execution.'],
  ['approval_rejected', 'A human rejected the held request.'],
  ['validation_failed', 'The parameters failed validation.'],
  ['handler_error', 'The capability failed after authorisation.'],
  ['intent_conflict', 'The request conflicts with an earlier intent.'],
] as const

const AGENT_ACCESS_MARKER = '<!-- generated by agentport -->'
const LLMS_BEGIN = '<!-- agentport:begin -->'
const LLMS_END = '<!-- agentport:end -->'

export function normaliseWorkerUrl(
  raw: string,
  tenantId?: string,
): { ok: true; url: string } | { ok: false; reason: string } {
  const value = (raw ?? '').trim()
  if (!value) return { ok: false, reason: 'AGENTPORT_WORKER_URL is not set — the hosted governor URL is required.' }
  let parsed: URL
  try {
    parsed = new URL(value)
  } catch {
    return { ok: false, reason: 'AGENTPORT_WORKER_URL is not a valid absolute URL.' }
  }
  if (parsed.protocol !== 'https:' && parsed.protocol !== 'http:') {
    return { ok: false, reason: 'AGENTPORT_WORKER_URL must be http or https.' }
  }
  if (parsed.protocol === 'http:' && !['localhost', '127.0.0.1', '::1'].includes(parsed.hostname)) {
    return { ok: false, reason: 'AGENTPORT_WORKER_URL must use https outside local development.' }
  }
  if (parsed.username || parsed.password || parsed.search || parsed.hash) {
    return { ok: false, reason: 'AGENTPORT_WORKER_URL must not carry credentials, a query or a fragment.' }
  }

  const path = parsed.pathname.replace(/\/+$/, '') || '/'
  if (tenantId === undefined) {
    return { ok: true, url: parsed.toString().replace(/\/$/, '') }
  }
  const tenant = tenantId.trim()
  if (!tenant) return { ok: false, reason: 'Tenant is missing; sign in again.' }
  const expected = `/t/${encodeURIComponent(tenant)}`
  if (path !== '/' && path !== expected) {
    return {
      ok: false,
      reason:
        path.startsWith('/t/')
          ? 'AGENTPORT_WORKER_URL names a different tenant than the signed-in workspace.'
          : 'AGENTPORT_WORKER_URL must be the hosted governor origin, not a path.',
    }
  }
  parsed.pathname = expected
  return { ok: true, url: parsed.toString().replace(/\/$/, '') }
}

function normaliseSiteUrl(raw: string | null | undefined): { ok: true; url: string | null } | { ok: false; reason: string } {
  if (raw === null || raw === undefined || raw.trim() === '') return { ok: true, url: null }
  const value = raw.trim()
  let parsed: URL
  try {
    parsed = new URL(value)
  } catch {
    return { ok: false, reason: 'The site URL is not a valid absolute URL.' }
  }
  if (parsed.protocol !== 'https:' && parsed.protocol !== 'http:') {
    return { ok: false, reason: 'The site URL must be http or https.' }
  }
  if (parsed.protocol === 'http:' && !['localhost', '127.0.0.1', '::1'].includes(parsed.hostname)) {
    return { ok: false, reason: 'The site URL must use https outside local development.' }
  }
  return { ok: true, url: parsed.toString().replace(/\/$/, '') }
}

/**
 * Pick where a framework serves static files. `public` and `static` are source
 * directories, so writing directly is enough. `out`/`dist`/`build` are build
 * outputs, so the package adds one postbuild hook instead of committing files
 * the next build would delete.
 *
 * A monorepo is inspected one level deeper: `apps/web/next.config.mjs` wins
 * over the repository root. If two packages both look like websites, the
 * caller gets `ambiguous` and must ask rather than commit into the wrong one.
 */
export function detectPublishTarget(paths: string[]): PublishTarget {
  const roots = new Set<string>([''])
  for (const path of paths) {
    const pkg = /^((?:[^/]+\/){1,2})package\.json$/.exec(path)
    if (pkg) roots.add(pkg[1]!.replace(/\/$/, ''))
    const config = /^((?:[^/]+\/){0,2})(?:next|vite|astro|nuxt|remix|svelte|gatsby)\.config\.[^.]+$/.exec(path)
    if (config) roots.add(config[1]!.replace(/\/$/, ''))
  }

  const candidates = [...roots]
    .sort((a, b) => a.split('/').length - b.split('/').length || a.localeCompare(b))
    .map((root) => targetAt(paths, root))
  const frameworkCandidates = candidates.filter(
    (target) => !['static', 'static-export', 'bundler', 'static-root'].includes(target.framework),
  )
  if (frameworkCandidates.length > 1) {
    return { ...frameworkCandidates[0]!, ambiguous: true }
  }
  if (frameworkCandidates.length === 1) return frameworkCandidates[0]!
  const nonDefault = candidates.find((target) => target.framework !== 'static-root')
  return nonDefault ?? candidates[0]!
}

function targetAt(paths: string[], root: string): PublishTarget {
  const at = (name: string): string => (root ? `${root}/${name}` : name)
  const hasFile = (name: string): boolean => paths.includes(name)
  const hasPrefix = (prefix: string): boolean =>
    paths.some((p) => p === prefix || p.startsWith(`${prefix}/`))
  const hasConfig = (base: string): boolean =>
    ['.js', '.mjs', '.cjs', '.ts', '.mts', '.cts'].some((ext) => hasFile(at(`${base}${ext}`)))
  const target = (dir: string, mode: PublishTarget['mode'], framework: string): PublishTarget => ({
    root,
    dir,
    mode,
    framework,
  })

  if (hasConfig('next.config')) return target('public', 'direct', 'next')
  if (hasConfig('vite.config')) return target('public', 'direct', 'vite')
  if (hasConfig('astro.config')) return target('public', 'direct', 'astro')
  if (hasConfig('nuxt.config')) return target('public', 'direct', 'nuxt')
  if (hasConfig('remix.config')) return target('public', 'direct', 'remix')
  if (hasConfig('svelte.config')) return target('static', 'direct', 'sveltekit')
  if (hasConfig('gatsby-config')) return target('static', 'direct', 'gatsby')
  if (hasPrefix(at('public'))) return target('public', 'direct', 'static')
  if (hasPrefix(at('static'))) return target('static', 'direct', 'static')
  if (hasPrefix(at('out'))) return target('out', 'build-output', 'static-export')
  if (hasPrefix(at('dist'))) return target('dist', 'build-output', 'bundler')
  if (hasPrefix(at('build'))) return target('build', 'build-output', 'bundler')
  return target('.', 'direct', 'static-root')
}

function targetPrefix(target: PublishTarget): string {
  const root = (target.root ?? '').replace(/^\/+|\/+$/g, '')
  const dir = target.dir === '.' ? '' : target.dir.replace(/^\/+|\/+$/g, '')
  const parts = [root, dir].filter((part) => part !== '')
  return parts.length === 0 ? '' : `${parts.join('/')}/`
}

function addBuildHook(packageJson: string): { ok: true; content: string } | { ok: false; reason: string } {
  let parsed: unknown
  try {
    parsed = JSON.parse(packageJson)
  } catch {
    return { ok: false, reason: 'package.json is not valid JSON; refusing to rewrite it.' }
  }
  if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) {
    return { ok: false, reason: 'package.json is not a JSON object; refusing to rewrite it.' }
  }
  const root = parsed as Record<string, unknown>
  const currentScripts =
    typeof root.scripts === 'object' && root.scripts !== null && !Array.isArray(root.scripts)
      ? ({ ...(root.scripts as Record<string, unknown>) } as Record<string, unknown>)
      : {}
  currentScripts['agentport:publish'] = 'node agentport/publish.mjs'
  const post = typeof currentScripts.postbuild === 'string' ? currentScripts.postbuild : ''
  if (!post.includes('agentport/publish.mjs')) {
    currentScripts.postbuild = post
      ? `${post} && node agentport/publish.mjs`
      : 'node agentport/publish.mjs'
  }
  root.scripts = currentScripts
  return { ok: true, content: `${JSON.stringify(root, null, 2)}\n` }
}

function capabilityDetails(compiled: Compiled, drafts: InstallPackageInput['drafts']) {
  const policy = compiled.policy
  let extra: Array<{ name: string; method: string; path: string; kind: 'read' | 'write' }> = []
  if (drafts.capabilities) {
    const validated = validateCapabilities(drafts.capabilities)
    if (validated.ok) extra = validated.value.extra ?? []
  }
  return compiled.capabilities.map((cap) => {
    const known = KNOWN_CAPABILITIES.find((c) => c.name === cap.name)
    const mapped = extra.find((c) => c.name === cap.name)
    const dataClass: DataClass =
      known?.dataClass ?? (cap.name === 'createOrder' ? 'payment' : 'internal')
    return {
      name: cap.name,
      description:
        known?.description ??
        (mapped ? `Mapped capability ${mapped.method} ${mapped.path}.` : `Capability ${cap.name}.`),
      access: known?.kind ?? mapped?.kind ?? 'write',
      dataClass,
      requiresApproval: (policy.alwaysRequireApproval ?? []).includes(cap.name),
      hiddenFields: cap.hiddenFields,
    }
  })
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}

function escapeMarkdown(value: string): string {
  return value.replace(/[\\`*_{}\[\]<>#|]/g, '\\$&')
}

function llmsTxt(business: string, manifestUrl: string, executeUrl: string): string {
  return [
    LLMS_BEGIN,
    `# Agent access — ${escapeMarkdown(business)}`,
    '',
    `Canonical manifest: ${manifestUrl}`,
    `Execute: ${executeUrl}`,
    '',
    'Authentication: a business-issued, short-lived credential with named scopes.',
    'Every call is evaluated and recorded by the hosted Agent Port governor.',
    'This file is a discovery pointer. It makes no policy decision.',
    LLMS_END,
    '',
  ].join('\n')
}

/**
 * `llms.txt` is shared: a site may already publish one. Replace only our
 * marked block and keep everything else byte-for-byte; append when absent.
 * Without this, a direct publish would replace the merchant's own file.
 */
function mergeLlmsTxt(existing: string | null | undefined, block: string): string {
  if (!existing) return block
  const start = existing.indexOf(LLMS_BEGIN)
  const end = existing.indexOf(LLMS_END)
  if (start !== -1 && end > start) {
    return existing.slice(0, start) + block + existing.slice(end + LLMS_END.length)
  }
  const separator = existing.endsWith('\n') ? '\n' : '\n\n'
  return `${existing}${separator}${block}`
}

function agentAccessHtml(business: string, manifestUrl: string): string {
  const safeBusiness = escapeHtml(business)
  const safeManifestUrl = escapeHtml(manifestUrl)
  return [
    '<!doctype html>',
    '<html lang="en">',
    '<head>',
    '  <meta charset="utf-8">',
    '  <meta name="viewport" content="width=device-width, initial-scale=1">',
    `  <title>Agent access — ${safeBusiness}</title>`,
    `  <link rel="alternate" type="application/json" href="${safeManifestUrl}">`,
    '  <meta name="agentport-manifest" content="' + safeManifestUrl + '">',
    '</head>',
    '<body>',
    `  <h1>${safeBusiness} — agent access</h1>`,
    '  <p>Agents use the manifest below. Every call is authorised and recorded by Agent Port.</p>',
    `  <p><a href="${safeManifestUrl}">${safeManifestUrl}</a></p>`,
    `  ${AGENT_ACCESS_MARKER}`,
    '</body>',
    '</html>',
    '',
  ].join('\n')
}

function readme(business: string, manifestUrl: string, target: PublishTarget): string {
  return [
    '# agentport/',
    '',
    `Discovery package for **${escapeMarkdown(business)}**.`,
    '',
    `Canonical manifest: ${manifestUrl}`,
    '',
    'This folder contains discovery files only. It has no policy engine, no',
    'credential, no ledger, no approval queue and no execution path. The hosted',
    'Agent Port governor evaluates every call and appends every decision.',
    '',
    '## Files',
    '',
    '- `manifest.json` — advisory snapshot of what this site exposes.',
    '- `config.json` — tenant and hosted-governor URLs. No secrets.',
    '- `llms.txt` — pointer for agents that read `llms.txt`.',
    '- `agent-access.html` — human/agent landing page.',
    '- `publish.mjs` — copies discovery files into the site.',
    '- `verify.mjs` — checks the deployed snapshot and the hosted manifest.',
    '',
    `This package lives in \`${target.root || '.'}\` and publishes into \`${target.dir}\` (${target.mode}).`,
    '',
    '## Update',
    '',
    'Regenerate from the dashboard and merge the PR. Do not hand-edit policy',
    'here; policy lives in the hosted governor and its audit trail.',
    '',
  ].join('\n')
}

function publishScript(): string {
  return `#!/usr/bin/env node
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const packageRoot = dirname(here)
const config = JSON.parse(readFileSync(join(here, 'config.json'), 'utf8'))
const target = config.publishDir === '.' ? packageRoot : join(packageRoot, config.publishDir)
const at = (rel) => join(target, rel)

mkdirSync(join(target, '.well-known'), { recursive: true })
copyFileSync(join(here, 'manifest.json'), at('.well-known/agent.json'))
copyFileSync(join(here, 'agent-access.html'), at('.well-known/agent-access.html'))

const begin = '<!-- agentport:begin -->'
const end = '<!-- agentport:end -->'
const block = readFileSync(join(here, 'llms.txt'), 'utf8').trim()
const llmsPath = at('llms.txt')
if (existsSync(llmsPath)) {
  const current = readFileSync(llmsPath, 'utf8')
  const start = current.indexOf(begin)
  const finish = current.indexOf(end)
  if (start >= 0 && finish > start) {
    writeFileSync(llmsPath, current.slice(0, start) + block + current.slice(finish + end.length))
  } else {
    writeFileSync(llmsPath, current.trimEnd() + '\\n\\n' + block + '\\n')
  }
} else {
  writeFileSync(llmsPath, block + '\\n')
}
console.log('agentport: wrote discovery into ' + config.publishDir)
`
}

function verifyScript(): string {
  return `#!/usr/bin/env node
import { createHash } from 'node:crypto'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const config = JSON.parse(readFileSync(join(here, 'config.json'), 'utf8'))
const fail = (message) => { console.error('agentport: ' + message); process.exit(1) }
const get = async (url) => {
  const res = await fetch(url, { headers: { accept: 'application/json' } })
  if (!res.ok) fail(url + ' returned ' + res.status)
  return res
}

const live = await (await get(config.manifestUrl)).json()
if (live.version !== '1.0') fail('hosted manifest version is not 1.0')
if (live.business !== config.business) fail('hosted manifest is for a different business')
if (live.authentication?.scheme !== 'bearer') fail('hosted manifest does not advertise bearer authentication')

if (config.siteUrl) {
  const staticUrl = new URL('/.well-known/agent.json', config.siteUrl).toString()
  const text = await (await get(staticUrl)).text()
  const digest = createHash('sha256').update(text).digest('hex')
  if (digest !== config.manifestSha256) fail('deployed manifest digest does not match the package')
}
console.log('agentport: discovery verified')
`
}

export function buildInstallPackageFrom(
  input: InstallPackageInput,
): { ok: true; value: InstallPackage } | { ok: false; reason: string } {
  const tenantId = (input.tenantId ?? '').trim()
  if (!tenantId) return { ok: false, reason: 'Tenant is missing; sign in again.' }
  const business = (input.business ?? '').trim()
  if (!business) return { ok: false, reason: 'Business name is missing; set it before opening an install PR.' }

  const worker = normaliseWorkerUrl(input.workerUrl, tenantId)
  if (!worker.ok) return worker
  const site = normaliseSiteUrl(input.siteUrl)
  if (!site.ok) return site

  const compiled = compileLiveFrom(input.drafts)
  if (!compiled.ok) return compiled

  const target = input.publishTarget ?? {
    root: '',
    dir: '.',
    mode: 'direct',
    framework: 'static-root',
  }
  if (target.ambiguous) {
    return {
      ok: false,
      reason:
        'More than one website package matched. Pick the package that serves the site before opening an install PR.',
    }
  }
  const root = (target.root ?? '').replace(/^\/+|\/+$/g, '')
  const dir = target.dir === '.' ? '.' : target.dir.replace(/^\/+|\/+$/g, '')
  if (root !== '' && !isSafeRepoPath(`${root}/.keep`)) {
    return { ok: false, reason: 'Package root is not a safe repository path.' }
  }
  if (dir !== '.' && !isSafeRepoPath(`${dir}/.keep`)) {
    return { ok: false, reason: 'Publish directory is not a safe repository path.' }
  }

  if (input.existingManifest) {
    try {
      const existing = JSON.parse(input.existingManifest) as { generatedBy?: unknown }
      if (existing.generatedBy !== 'agentport') {
        return {
          ok: false,
          reason:
            'A different agent manifest already exists at this path. Refusing to overwrite it; move it or remove it first.',
        }
      }
    } catch {
      return {
        ok: false,
        reason:
          'An existing agent manifest is not valid JSON. Refusing to overwrite it; review it first.',
      }
    }
  }
  if (input.existingAccessPage && !input.existingAccessPage.includes(AGENT_ACCESS_MARKER)) {
    return {
      ok: false,
      reason:
        'A different agent-access page already exists. Refusing to overwrite it; move it or remove it first.',
    }
  }

  const now = input.now ?? new Date()
  const manifestUrl = `${worker.url}/.well-known/agent.json`
  const executeUrl = `${worker.url}/.well-known/agent/invoke`
  const details = capabilityDetails(compiled.compiled, input.drafts)
  const policy = compiled.compiled.policy
  const manifest: Record<string, unknown> = {
    version: '1.0',
    generatedBy: 'agentport',
    business,
    baseUrl: worker.url,
    generatedAt: now.toISOString(),
    capabilities: details,
    authentication: {
      required: true,
      scheme: 'bearer',
      credential: 'business-issued, short-lived token with named scopes',
      note: 'An agent is never trusted for being an agent. The hosted governor verifies the credential before policy evaluation.',
    },
    policies: {
      ...(policy.maxOrderValue ? { maxOrderValue: policy.maxOrderValue } : {}),
      ...(policy.absoluteMaxOrderValue
        ? { absoluteMaxOrderValue: policy.absoluteMaxOrderValue }
        : {}),
      ...(policy.bulkOrderThreshold ? { bulkOrderThreshold: policy.bulkOrderThreshold } : {}),
      ...(policy.rateLimit ? { rateLimit: policy.rateLimit } : {}),
      requiresApproval: policy.alwaysRequireApproval ?? [],
      forbiddenCapabilities: policy.forbiddenCapabilities ?? [],
      restrictedDataClasses: policy.restrictedDataClasses ?? [],
    },
    errorContract: DENIAL_REASONS.map(([reason, meaning]) => ({ reason, meaning })),
    endpoints: { manifest: manifestUrl, execute: executeUrl },
    note: 'Advisory discovery snapshot. The hosted governor serves the authoritative manifest and makes every decision.',
  }
  const manifestContent = `${JSON.stringify(manifest, null, 2)}\n`
  const manifestSha256 = createHash('sha256').update(manifestContent).digest('hex')
  const config: Record<string, unknown> = {
    version: 1,
    generatedBy: 'agentport',
    tenantId,
    business,
    siteUrl: site.url,
    workerUrl: worker.url,
    manifestUrl,
    executeUrl,
    manifestSha256,
    packageRoot: root === '' ? '.' : root,
    publishDir: dir,
    issuedAt: now.toISOString(),
    enforcement: 'hosted',
    note: 'Discovery only. No policy decision, credential, ledger, approval queue or execution path lives here.',
  }

  const normalisedTarget: PublishTarget = { ...target, root, dir }
  const packagePrefix = root === '' ? '' : `${root}/`
  const prefix = targetPrefix(normalisedTarget)
  const packageJsonPath = `${packagePrefix}package.json`
  const files: InstallFile[] = [
    { path: `${packagePrefix}agentport/manifest.json`, content: manifestContent },
    { path: `${packagePrefix}agentport/config.json`, content: `${JSON.stringify(config, null, 2)}\n` },
    { path: `${packagePrefix}agentport/llms.txt`, content: llmsTxt(business, manifestUrl, executeUrl) },
    { path: `${packagePrefix}agentport/agent-access.html`, content: agentAccessHtml(business, manifestUrl) },
    { path: `${packagePrefix}agentport/publish.mjs`, content: publishScript() },
    { path: `${packagePrefix}agentport/verify.mjs`, content: verifyScript() },
    { path: `${packagePrefix}agentport/README.md`, content: readme(business, manifestUrl, normalisedTarget) },
  ]

  if (target.mode === 'direct') {
    files.push(
      { path: `${prefix}.well-known/agent.json`, content: manifestContent },
      { path: `${prefix}.well-known/agent-access.html`, content: agentAccessHtml(business, manifestUrl) },
      { path: `${prefix}llms.txt`, content: mergeLlmsTxt(input.existingLlms, llmsTxt(business, manifestUrl, executeUrl)) },
    )
  } else {
    if (!input.packageJson) {
      return {
        ok: false,
        reason: `This site builds to ${dir}/, so the install needs a postbuild hook, but ${packageJsonPath} was not found.`,
      }
    }
    const hooked = addBuildHook(input.packageJson)
    if (!hooked.ok) return hooked
    files.push({ path: packageJsonPath, content: hooked.content })
  }

  for (const file of files) {
    if (!isSafeRepoPath(file.path)) {
      return { ok: false, reason: `Refusing to write an unsafe path: ${file.path}` }
    }
  }
  const unique = new Set(files.map((f) => f.path))
  if (unique.size !== files.length) {
    return { ok: false, reason: 'Install package contains duplicate file paths.' }
  }

  return {
    ok: true,
    value: { files, target: normalisedTarget, manifest, config, summary: compiled.compiled.summary },
  }
}

/**
 * A single-file manual path for merchants who are not ready to grant the App
 * repo access. It writes the same package; it does not evaluate anything.
 */
export function buildManualInstaller(files: InstallFile[]): string {
  const payload = JSON.stringify(files)
  return `#!/usr/bin/env node
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

const files = ${payload}
for (const file of files) {
  const target = join(process.cwd(), file.path)
  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, file.content, { encoding: 'utf8', mode: 0o644 })
}
console.log('agentport: wrote ' + files.length + ' files. Review the diff, then commit.')
`
}
