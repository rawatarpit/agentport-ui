export function detectIndustryKey(profile: ResearchProfile): string {
  const text = `${profile.industry ?? ''} ${profile.subIndustry ?? ''}`.toLowerCase()
  for (const industry of INDUSTRIES) {
    if (industry.patterns.test(text)) return industry.industryKey
  }
  return GENERAL.industryKey
}

export function buildWorkflows(profile: ResearchProfile): AgentWorkflow[] {
  const industryKey = detectIndustryKey(profile)
  const templates =
    INDUSTRIES.find((industry) => industry.industryKey === industryKey)?.workflows ?? GENERAL.workflows
  const evidenceStatement = `Hypothesis derived from the submitted profile for ${industryKey}. It is not a verified capability and rests on no external evidence or market metric.`

  return templates.map((template) => ({
    ...template,
    id: `${industryKey}:${template.id}`,
    industryKey,
    requiredData: [...template.requiredData],
    technicalDependencies: [...template.technicalDependencies],
    evidenceStatement,
    evidenceProvenance: 'interpretation',
    confidence: 'low',
    verifiedCapability: false,
    sourceIds: [],
  }))
}
